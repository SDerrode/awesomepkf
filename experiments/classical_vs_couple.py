"""Classical vs. couple smoothing under measurement back-action (SPL paper, Sec. III).

Data are generated by a *true* pairwise model whose latent state is partly driven
by the observed channel (measurement back-action ``A^{xy} != 0``) with correlated
process noise (``R^{xy} != 0``). Three fixed-interval smoothers process the SAME
record:

  * couple            : the correct pairwise model (VAR / lifted solve);
  * classical (ablated): the same model with the couple-specific terms deleted
                         (``A^{xy}=0``, ``R^{xy}=0``) but the retained blocks frozen
                         at their true values -- isolates the Y->X channel;
  * classical (refit)  : the *population-optimal* classical model, i.e. the best
                         member of the classical class (``A^{xy}=0``, ``R^{xy}=0``)
                         fitted to the true stationary moments of the pairwise
                         process (closed-form constrained regression via the
                         Lyapunov covariance). This is a best-case steelman: even
                         with oracle knowledge of the process it cannot represent
                         Y->X, so a residual gap survives.

We sweep the coupling strength ``rho`` (scales both ``A^{xy}`` and ``R^{xy}``) and
report, against ground truth, the smoothed-state MSE and the normalised estimation
error squared (NEES/dim X, calibrated value = 1), with +/- 1 s.e. bands over seeds.

Run (with ``prg`` importable, e.g. from the awesomepkf repo root):
    python experiments/classical_vs_couple.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.linalg import solve_discrete_lyapunov

from prg.classes.linear_pkf import Linear_PKF
from prg.classes.linear_pks import Linear_PKS_VAR
from prg.classes.param_linear import ParamLinear
from prg.models.linear._amq import LinearAmQ

DX, DY, DZ = 1, 1, 2
AXX, AYX, AYY = 0.6, 0.3, 0.4          # blocks shared by both models
AXY_BAR, S_BAR = 0.4, 0.05            # couple-specific terms, scaled by rho
QXX, QYY = 0.10, 0.10
inv = np.linalg.inv


def _A(rho: float) -> np.ndarray:
    return np.array([[AXX, rho * AXY_BAR], [AYX, AYY]])


def _Q(rho: float) -> np.ndarray:
    return np.array([[QXX, rho * S_BAR], [rho * S_BAR, QYY]])


def _param(A: np.ndarray, Q: np.ndarray) -> ParamLinear:
    Qs = 0.5 * (Q + Q.T) + 1e-9 * np.eye(DZ)
    m = LinearAmQ(DX, DY, A=A, mQ=Qs, mz0=np.zeros((DZ, 1)),
                  Pz0=np.eye(DZ), pairwiseModel=True)
    p = m.get_params().copy()
    p.pop("dim_x")
    p.pop("dim_y")
    return ParamLinear(0, DX, DY, **p)


def _best_classical_param(A: np.ndarray, Q: np.ndarray) -> ParamLinear:
    """Population-optimal classical model (A^{xy}=0, R^{xy}=0) for the true couple.

    Uses the stationary second moments of the true pairwise process: with
    ``Sig`` its Lyapunov covariance, ``M0=E[Z_nZ_n^T]=Sig`` and
    ``M1=E[Z_{n+1}Z_n^T]=A Sig``, the classical-constrained MLE regresses X on X
    only and Y on (X,Y), with block-diagonal residual covariance.
    """
    Sig = solve_discrete_lyapunov(A, 0.5 * (Q + Q.T))
    M0, M1 = Sig, A @ Sig
    Ac = np.zeros((DZ, DZ))
    Ac[:DX, :DX] = M1[:DX, :DX] @ inv(M0[:DX, :DX])       # A^{xx}, no back-action
    Ac[DX:, :] = M1[DX:, :] @ inv(M0)                     # [A^{yx}, A^{yy}]
    Qc = np.zeros((DZ, DZ))
    Qc[:DX, :DX] = Sig[:DX, :DX] - Ac[:DX, :DX] @ M1[:DX, :DX].T
    Qc[DX:, DX:] = Sig[DX:, DX:] - Ac[DX:, :] @ M1[DX:, :].T
    return _param(Ac, Qc)


def _smooth(param: ParamLinear, data) -> list:
    sm = Linear_PKS_VAR(param)
    sm.process_N_data_smoother(N=len(data) - 1, data_generator=iter(data))
    return sm.history


def _metrics(history, data) -> tuple[float, float]:
    """Smoothed-state MSE and NEES against the simulated ground-truth X."""
    se = nees = 0.0
    n = 0
    for h, (_k, x, _y) in zip(history, data, strict=True):
        xt = np.asarray(x, float).reshape(DX, 1)
        xh = np.asarray(h["Xkp1_smooth"], float).reshape(DX, 1)
        P = np.asarray(h["PXXkp1_smooth"], float).reshape(DX, DX)
        e = xt - xh
        se += (e.T @ e).item()
        nees += (e.T @ np.linalg.solve(P, e)).item()
        n += 1
    return se / n, nees / (n * DX)      # NEES/dim X: calibrated = 1 (DX=1 here)


NAMES = ("couple", "ablated", "refit")


def main(N: int = 400, seeds: int = 200, n_rho: int = 9) -> dict:
    rhos = np.linspace(0.0, 1.0, n_rho)
    p_ablated = _param(_A(0.0), _Q(0.0))                  # frozen retained blocks
    res = {"rho": list(rhos)}
    for name in NAMES:
        res[f"mse_{name}"] = []
        res[f"mse_{name}_se"] = []
        res[f"nees_{name}"] = []
        res[f"nees_{name}_se"] = []
    print(f"{'rho':>5} | {'MSE couple':>10} {'ablated':>9} {'refit':>9} "
          f"| {'NEES cpl':>8} {'abl':>6} {'refit':>6}")
    for rho in rhos:
        p_couple = _param(_A(rho), _Q(rho))
        p_refit = _best_classical_param(_A(rho), _Q(rho))
        models = {"couple": p_couple, "ablated": p_ablated, "refit": p_refit}
        mse = {k: [] for k in NAMES}
        nees = {k: [] for k in NAMES}
        for s in range(seeds):
            data = Linear_PKF(p_couple, sKey=s).simulate_N_data(N)
            for name in NAMES:
                a, b = _metrics(_smooth(models[name], data), data)
                mse[name].append(a)
                nees[name].append(b)
        for name in NAMES:
            m, nn = np.asarray(mse[name]), np.asarray(nees[name])
            res[f"mse_{name}"].append(m.mean())
            res[f"mse_{name}_se"].append(m.std(ddof=1) / np.sqrt(seeds))
            res[f"nees_{name}"].append(nn.mean())
            res[f"nees_{name}_se"].append(nn.std(ddof=1) / np.sqrt(seeds))
        print(f"{rho:>5.2f} | {res['mse_couple'][-1]:>10.4f} "
              f"{res['mse_ablated'][-1]:>9.4f} {res['mse_refit'][-1]:>9.4f} | "
              f"{res['nees_couple'][-1]:>8.2f} {res['nees_ablated'][-1]:>6.2f} "
              f"{res['nees_refit'][-1]:>6.2f}")
    mc, ma, mr = res["mse_couple"][-1], res["mse_ablated"][-1], res["mse_refit"][-1]
    print(f"\nAt rho=1: vs couple, ablated MSE +{100*(ma/mc-1):.0f}% (NEES "
          f"{res['nees_ablated'][-1]:.2f}); refit MSE +{100*(mr/mc-1):.0f}% (NEES "
          f"{res['nees_refit'][-1]:.2f}); couple NEES {res['nees_couple'][-1]:.2f}.")
    np.savez(_CACHE, **{k: np.asarray(v, float) for k, v in res.items()})
    print(f"data cached to {_CACHE}")
    _plot(res)
    return res


_CACHE = Path(__file__).resolve().parents[1] / "figures" / "classical_vs_couple_data.npz"


def _replot_from_cache() -> dict:
    """Re-render the figure from the cached MC arrays (instant; no re-simulation).

    The heavy part is the seeded MC sweep; the numbers are deterministic, so once
    cached, any style/colour tweak only needs ``--replot`` instead of ~10 min of
    library smoothing.
    """
    d = np.load(_CACHE)
    res = {k: d[k] for k in d.files}
    _plot(res)
    return res


def _plot(res: dict) -> None:
    import matplotlib as mpl
    mpl.use("Agg")
    # Shared paper figure style. Set AFTER any awesomepkf/prg plot_settings import
    # (those ran at module import time above) so these rcParams win; explicit
    # colors are given on every plot call so nothing is left to a prop_cycle.
    mpl.rcParams.update({
        "figure.dpi": 150, "savefig.dpi": 300, "savefig.facecolor": "white",
        "savefig.bbox": "tight", "font.size": 8, "axes.titlesize": 8.5,
        "axes.labelsize": 8, "xtick.labelsize": 7, "ytick.labelsize": 7,
        "legend.fontsize": 7, "legend.framealpha": 0.9, "lines.linewidth": 1.3,
        "lines.markersize": 4, "axes.axisbelow": True,
    })
    import matplotlib.pyplot as plt

    rho = np.asarray(res["rho"])
    # Harmonized palette: couple=C0 (blue), refit=C1 (orange),
    # ablated="0.5" (gray) dashed -- matches Figs 4-5.
    style = {"couple": ("o-", "tab:blue", "couple"),
             "refit": ("^-.", "tab:orange", "classical (refit)"),
             "ablated": ("s--", "0.5", "classical (ablated)")}
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.6))
    for name in ("couple", "refit", "ablated"):
        mk, col, lab = style[name]
        m = np.asarray(res[f"mse_{name}"]); se = np.asarray(res[f"mse_{name}_se"])
        ax1.plot(rho, m, mk, ms=4, color=col, label=lab)
        ax1.fill_between(rho, m - se, m + se, color=col, alpha=0.20, lw=0)
    ax1.set_xlabel(r"coupling strength $\rho$")
    ax1.set_ylabel("smoothed-state MSE")
    ax1.legend()
    ax1.grid(True, alpha=0.3)

    ax2.axhline(DX, ls=":", color="k", lw=1, label="calibrated")
    for name in ("couple", "refit", "ablated"):
        mk, col, lab = style[name]
        m = np.asarray(res[f"nees_{name}"]); se = np.asarray(res[f"nees_{name}_se"])
        ax2.plot(rho, m, mk, ms=4, color=col, label=lab)
        ax2.fill_between(rho, m - se, m + se, color=col, alpha=0.20, lw=0)
    ax2.set_xlabel(r"coupling strength $\rho$")
    ax2.set_ylabel("NEES")
    ax2.legend()
    ax2.grid(True, alpha=0.3)

    fig.tight_layout()
    out = Path(__file__).resolve().parents[1] / "figures" / "classical_vs_couple.pdf"
    out.parent.mkdir(exist_ok=True)
    fig.savefig(out)                       # vector PDF
    fig.savefig(out.with_suffix(".png"))   # raster preview beside it
    print(f"figure written to {out}")
    print(f"preview written to {out.with_suffix('.png')}")


if __name__ == "__main__":
    import sys
    if "--replot" in sys.argv:          # instant re-render from cached MC arrays
        _replot_from_cache()
    else:
        main()
